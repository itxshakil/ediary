@section('article')
    <p class="text-xl leading-relaxed font-medium text-gray-600 italic md:text-2xl dark:text-gray-400">
        Diaries are wonderful objects that allow you to discuss your emotions, record dreams or ideas, and reflect on
        daily life in a safe, private space.
    </p>

    <p>
        While there's no single, definitive way to write a diary, there are some basic tricks you can use to get the
        most out of your writing. If you aren't sure what to write about, using prompts like inspirational quotes can
        help get started on new entries.
    </p>

    <p>
        You can write about anything that you want in your diary, but sometimes it's hard to get started. An easy way to
        start a diary entry is to just write about your day. Write about your morning before work or school, what you
        had for lunch, your ride home, and anything else you did that day.
    </p>

    <h2>Brainstorming Ideas</h2>

    <h3>Write about the events of your day</h3>
    <p>
        Think about everything that happened that day and record any highlights or feelings that stand out to you. Even
        if you had a pretty standard day, you might be surprised by deeper thoughts and feelings that come up as you
        write down details about your day.
    </p>
    <ul>
        <li>Feel free to veer off into any topic you want as you're writing about the day's events.</li>
        <li>
            For example, you could write about an English exam. Are you feeling good about it? Do you wish you had
            studied more?
        </li>
    </ul>

    <h3>Contemplate your goals for the future</h3>
    <p>
        Make a list of your short-term and long-term goals. Then, go through each item on the list and write in detail
        about your plan to accomplish the goal. Breaking each goal up into smaller tasks that you can work on can make
        your goals feel less overwhelming.
    </p>

    <h3>Jot down your current feelings or mood</h3>
    <p>
        Don't worry about providing any context for your emotions, just focus on accurately describing what they are.
        You can then use those feelings and thoughts as prompts for creating detailed diary entries.
    </p>

    <h3>Write down inspirational quotes</h3>
    <p>
        Inspirational quotes can come from anywhere—a famous person, your favorite book, or even a friend. Record the
        quote in your diary and explain what it means to you in your own words.
    </p>

    <h3>Explore your favorite subjects in-depth</h3>
    <p>
        Make a list of topics that you love: movies, sports, food, travel, art, or fashion. Then, choose one item from
        the list and create a diary entry about it.
    </p>

    <h2>Writing Meaningful Entries</h2>

    <h3>Write the date in the corner</h3>
    <p>
        Dating your entries can help you keep track of when things happened. Dates will also help you stay organized and
        provide context when you look back in the future.
    </p>

    <h3>Begin each entry with a topic in mind</h3>
    <p>
        Having something in mind when you start the entry can help kickstart the writing process. Once you start, you're
        free to veer off into any subject you like!
    </p>

    <h3>Write in the first person</h3>
    <p>
        Diaries are very personal, and they typically work best when you speak in the first person using "I" statements.
        In your diary, you are free to make everything about you!
    </p>

    <h3>Be honest in your entries</h3>
    <p>
        Feel free to record your emotions, both positive and negative. Remember that no one will ever see what you've
        written, so you can write honestly about anything. This is for your eyes only.
    </p>

    <h3>Don't worry too much about grammar</h3>
    <p>
        Your diary is a safe space for you to vent without the pressures of external judgment. Proper spelling and
        perfect phrases are not nearly as important as getting your thoughts down.
    </p>

    <h2>Developing the Habit</h2>

    <h3>Choose a specific time each day</h3>
    <p>
        Choose a specific time each day for diary writing so that you can develop the habit. Eventually, it will become
        second nature.
    </p>

    <h3>Keep your writing sessions short in the beginning</h3>
    <p>
        You don't have to set aside a huge chunk of time! 10-15 minutes per session is a great goal when you're just
        starting out.
    </p>
@endsection
